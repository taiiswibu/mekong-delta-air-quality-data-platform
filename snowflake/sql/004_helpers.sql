USE WAREHOUSE AQ_WH;
USE DATABASE AQ_WAREHOUSE;
USE SCHEMA CONTROL;

CREATE OR REPLACE PROCEDURE PRUNE_OBSERVABILITY(retention_days INTEGER)
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN
  DELETE FROM CONTROL.PIPELINE_TASK_EVENTS
   WHERE event_at < DATEADD(DAY, -1 * :retention_days, CURRENT_TIMESTAMP());
  DELETE FROM CONTROL.PIPELINE_METRICS
   WHERE captured_at < DATEADD(DAY, -1 * :retention_days, CURRENT_TIMESTAMP());
  DELETE FROM CONTROL.DQ_RESULTS
   WHERE checked_at < DATEADD(DAY, -1 * :retention_days, CURRENT_TIMESTAMP());
  RETURN 'observability data pruned';
END;
$$;
